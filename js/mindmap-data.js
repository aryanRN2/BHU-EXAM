/**
 * Dynamically builds a structured Mind Map object from a standard course syllabus JSON object.
 */
function buildMindMapFromPaper(paper, deptName = "Department") {
  if (!paper) return null;
  const code = paper.code || "COURSE";
  
  if (PREDEFINED_MINDMAPS[code]) {
    return PREDEFINED_MINDMAPS[code];
  }

  const unitColors = ["#4F46E5", "#0891B2", "#D97706", "#059669", "#7C3AED", "#DB2777", "#2563EB"];

  const rootNode = {
    id: "root",
    label: paper.name || "Course Syllabus",
    badge: `${code} • Sem ${paper.semester || 'UG'}`,
    type: "root",
    details: `${paper.credits || 4} Credits ${paper.course_type || 'Core'} Course. Syllabus breakdown tree.`,
    children: []
  };

  if (paper.syllabus && Array.isArray(paper.syllabus)) {
    paper.syllabus.forEach((u, idx) => {
      const color = unitColors[idx % unitColors.length];
      const unitNode = {
        id: `unit_${u.unit}`,
        label: `Unit ${u.unit}`,
        badge: `Unit ${u.unit}`,
        type: "unit",
        color: color,
        details: u.topics || "",
        children: []
      };

      // Split topics by sentence or punctuation to create subtopic nodes
      if (u.topics) {
        const rawTopics = u.topics
          .replace(/\d+\s*(Texts|Course Title|Hours)?.*$/gi, '') // Clean tail numbers
          .split(/(?:\.|\;|\:)\s+/)
          .map(t => t.trim())
          .filter(t => t.length > 2);

        rawTopics.forEach((t, tIdx) => {
          unitNode.children.push({
            id: `u${u.unit}_t${tIdx+1}`,
            label: t,
            type: "topic",
            details: t
          });
        });
      }

      rootNode.children.push(unitNode);
    });
  }

  return {
    id: code,
    code: code,
    title: paper.name,
    department: deptName,
    credits: paper.credits,
    course_type: paper.course_type,
    root: rootNode
  };
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { PREDEFINED_MINDMAPS, buildMindMapFromPaper };
}
